                new Product { BusinessId = defaultBiz.Id, Name = "Espresso Roast 1kg", Category = "Coffee Beans", Price = 850m, Cost = 550m, CurrentStock = 18, LowStockAlert = 5 },
                new Product { BusinessId = defaultBiz.Id, Name = "Brown Sugar Syrup 2L", Category = "Syrups", Price = 420m, Cost = 260m, CurrentStock = 3, LowStockAlert = 5 },
