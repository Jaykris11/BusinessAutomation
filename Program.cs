        }
        await db.SaveChangesAsync();

        // 6. Seed Sample Products / Stocks & Alerts
        if (!await db.Products.AnyAsync(p => p.BusinessId == defaultBiz.Id))
        {
            db.Products.AddRange(new[]
            {
