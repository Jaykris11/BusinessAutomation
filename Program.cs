            {
                db.Workers.Add(new Worker
                {
                    BusinessId = defaultBiz.Id,
                    UserId = wUser.Id,
                    FullName = sw.Name,
                    PayType = sw.PayType,
                    Rate = sw.Rate,
                    HoursPerDay = sw.Hours,
                    IsActive = true
                });
