            );
            CREATE TABLE IF NOT EXISTS ""Sales"" (
                ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""BusinessId"" integer NOT NULL,
                ""TotalAmount"" numeric(12,2) NOT NULL,
