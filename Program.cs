                ""ClosedAtUtc"" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
                ""Notes"" text
            );
        ";
        await db.Database.ExecuteSqlRawAsync(createScript);

        var dbCreator = db.Database.GetService<IRelationalDatabaseCreator>();
        if (!dbCreator.HasTables())
        {
            dbCreator.CreateTables();
        }

        // 1. Roles
        if (!await roleMgr.RoleExistsAsync("Owner")) await roleMgr.CreateAsync(new IdentityRole("Owner"));
        if (!await roleMgr.RoleExistsAsync("Employee")) await roleMgr.CreateAsync(new IdentityRole("Employee"));

        // 2. Default Business
        if (!await db.Businesses.AnyAsync())
        {
            var biz = new Business { Name = "Laufey Business", RequireIpForPunch = true };
            db.Businesses.Add(biz);
            await db.SaveChangesAsync();
        }

        var defaultBiz = await db.Businesses.FirstAsync();

        // 3. Allowed Store IP (Wi-Fi)
        if (!await db.AllowedIps.AnyAsync(a => a.BusinessId == defaultBiz.Id))
        {
            db.AllowedIps.Add(new AllowedIp
            {
                BusinessId = defaultBiz.Id,
                Address = "127.0.0.1",
                Label = "Main Store Wi-Fi (Localhost)"
            });
            db.AllowedIps.Add(new AllowedIp
            {
                BusinessId = defaultBiz.Id,
                Address = "::1",
