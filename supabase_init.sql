-- 1. Create ASP.NET Identity Core Tables
CREATE TABLE IF NOT EXISTS "AspNetRoles" (
    "Id" text NOT NULL PRIMARY KEY,
    "Name" character varying(256),
    "NormalizedName" character varying(256),
    "ConcurrencyStamp" text
);

CREATE TABLE IF NOT EXISTS "AspNetUsers" (
    "Id" text NOT NULL PRIMARY KEY,
    "UserName" character varying(256),
    "NormalizedUserName" character varying(256),
    "Email" character varying(256),
    "NormalizedEmail" character varying(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text,
    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL
);

CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "ClaimType" text,
    "ClaimValue" text
);

CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text,
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("LoginProvider", "ProviderKey")
);

CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "RoleId" text NOT NULL REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("UserId", "RoleId")
);

CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
    "UserId" text NOT NULL REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text,
    PRIMARY KEY ("UserId", "LoginProvider", "Name")
);

-- 2. Create Payroll Business Tables
CREATE TABLE IF NOT EXISTS "Businesses" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" text NOT NULL,
    "RequireIpForPunch" boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS "AllowedIps" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL REFERENCES "Businesses" ("Id") ON DELETE CASCADE,
    "Address" text NOT NULL,
    "Label" text
);

CREATE TABLE IF NOT EXISTS "Workers" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "UserId" text,
    "FullName" text NOT NULL,
    "PayType" integer NOT NULL,
    "Rate" numeric(12,2) NOT NULL,
    "HoursPerDay" numeric(5,2) NOT NULL,
    "IsActive" boolean NOT NULL,
    "ShiftStart" text NOT NULL DEFAULT '09:00',
    "ShiftEnd" text NOT NULL DEFAULT '18:00',
    "LunchStart" text NOT NULL DEFAULT '12:00',
    "LunchEnd" text NOT NULL DEFAULT '13:00'
);

CREATE TABLE IF NOT EXISTS "Punches" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "WorkerId" integer NOT NULL,
    "Type" integer NOT NULL,
    "TimestampUtc" timestamp with time zone NOT NULL,
    "IpAddress" text,
    "SelfiePath" text
);

CREATE TABLE IF NOT EXISTS "RejectedPunches" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "WorkerId" integer NOT NULL,
    "TimestampUtc" timestamp with time zone NOT NULL,
    "IpAddress" text,
    "Reason" text NOT NULL
);

CREATE TABLE IF NOT EXISTS "AuditLogs" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "ActorUserId" text NOT NULL,
    "Action" text NOT NULL,
    "OldValue" text,
    "NewValue" text,
    "Reason" text,
    "TimestampUtc" timestamp with time zone NOT NULL
);

-- 2.1 Products / Stock Inventory
CREATE TABLE IF NOT EXISTS "Products" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "Name" text NOT NULL,
    "Category" text NOT NULL DEFAULT 'General',
    "Price" numeric(12,2) NOT NULL DEFAULT 0,
    "Cost" numeric(12,2) NOT NULL DEFAULT 0,
    "CurrentStock" integer NOT NULL DEFAULT 0,
    "LowStockAlert" integer NOT NULL DEFAULT 10,
    "IsActive" boolean NOT NULL DEFAULT true
);

-- 2.2 Sales Tracking
CREATE TABLE IF NOT EXISTS "Sales" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "TotalAmount" numeric(12,2) NOT NULL,
    "PaymentMethod" text NOT NULL DEFAULT 'Cash',
    "ReferenceNumber" text,
    "Notes" text,
    "TimestampUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2.3 Store Announcements
CREATE TABLE IF NOT EXISTS "Announcements" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "Title" text NOT NULL,
    "Message" text NOT NULL,
    "Priority" text NOT NULL DEFAULT 'Normal',
    "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "IsActive" boolean NOT NULL DEFAULT true
);

-- 2.4 End-of-Day Cash Drawer Closing (Z-Read)
CREATE TABLE IF NOT EXISTS "CashDrawerClosings" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "CashDrawerActual" numeric(12,2) NOT NULL,
    "ExpectedSales" numeric(12,2) NOT NULL,
    "Difference" numeric(12,2) NOT NULL,
    "Status" text NOT NULL DEFAULT 'Balanced',
    "ClosedBy" text NOT NULL DEFAULT 'Owner',
    "ClosedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "Notes" text
);

-- 2.5 Leave / PTO / VTO Requests
CREATE TABLE IF NOT EXISTS "LeaveRequests" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "WorkerId" integer NOT NULL,
    "Type" integer NOT NULL DEFAULT 0,
    "TargetDate" timestamp with time zone NOT NULL,
    "Reason" text NOT NULL,
    "Status" integer NOT NULL DEFAULT 0,
    "OwnerNote" text,
    "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "ReviewedAtUtc" timestamp with time zone
);

-- 2.6 Cash Advance / Vale Requests
CREATE TABLE IF NOT EXISTS "AdvancePaymentRequests" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "WorkerId" integer NOT NULL,
    "AmountRequested" numeric(12,2) NOT NULL,
    "Reason" text NOT NULL,
    "Status" integer NOT NULL DEFAULT 0,
    "OwnerNote" text,
    "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "ReviewedAtUtc" timestamp with time zone
);

-- 2.7 Store Shift Sessions (Start / Stop Store Shift)
CREATE TABLE IF NOT EXISTS "StoreShiftSessions" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "ShiftName" text NOT NULL DEFAULT 'Morning Shift',
    "StartedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "EndedAtUtc" timestamp with time zone,
    "IsActive" boolean NOT NULL DEFAULT true,
    "StartedBy" text NOT NULL DEFAULT 'Owner',
    "EndedBy" text
);

-- 2.8 Payslips / Payment Slips
CREATE TABLE IF NOT EXISTS "Payslips" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BusinessId" integer NOT NULL,
    "WorkerId" integer NOT NULL,
    "PayPeriod" text NOT NULL,
    "HoursWorked" numeric(8,2) NOT NULL DEFAULT 0,
    "HourlyRate" numeric(12,2) NOT NULL DEFAULT 0,
    "GrossPay" numeric(12,2) NOT NULL DEFAULT 0,
    "CashAdvanceDeductions" numeric(12,2) NOT NULL DEFAULT 0,
    "OtherDeductions" numeric(12,2) NOT NULL DEFAULT 0,
    "NetPay" numeric(12,2) NOT NULL DEFAULT 0,
    "PaymentMethod" text NOT NULL DEFAULT 'Cash',
    "Remarks" text,
    "IssuedAtUtc" timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    "IsAcknowledged" boolean NOT NULL DEFAULT false,
    "AcknowledgedAtUtc" timestamp with time zone,
    "IsArchived" boolean NOT NULL DEFAULT false
);

